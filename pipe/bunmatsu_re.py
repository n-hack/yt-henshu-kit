# 話した字の「文の終わり」（台本に無い言い足しの中でも字幕を切る所）：〜です／ます／ました／でした／ません の後に、続きの字が来ない所
#   続き＝よ・ね・か・が・けど・し・ので・の・と・って・ん・わ・もん・もの・ら・な・や・ます（ますます）・でしょ・じゃ（10/20 r14 で作業AIが見つけた「思います優秀な」「能動型AIです自分で」から）
#   jimaku_ji.py（切れ目を入れる）・kire_auto.py（印を残す・行をつながない）・jimaku_bunmatsu.py（数える）が同じ式を使う
import re
OWARI = re.compile(r'(?:です|ます|ました|でした|ません)(?!よ|ね|か|が|けど|けれ|し|ので|のに|の|と|って|っ|ん|わ|もん|もの|ら|な|や|ます|でしょ|じゃ)(?=.)')
def owari_de_owaru(s):
    """s が文の終わりで終わっているか（行の終わり・札の終わりで使う）"""
    return bool(re.search(r'(?:です|ます|ました|でした|ません)$', s))
